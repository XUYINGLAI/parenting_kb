import dashscope

from atguigu.config.config import RerankConfig
from atguigu.query_process.base import NodeBase
from atguigu.query_process.state import QueryGraphState
from atguigu.tool.json_format import json_format
from atguigu.tool.logger import logger



class NodeRerank(NodeBase):
    """
    节点功能：使用 Cross-Encoder 模型对 RRF 后的结果进行精确打分重排。
    """

    # 覆盖基类的 name 属性，标识节点名称
    name: str = "node_rerank"

    def process(self, state: QueryGraphState):
        logger.info(f"【{self.name}】节点逻辑")
        rewritten_query=state.get("rewritten_query")
        rrf_chunks=state.get("rrf_chunks")
        web_search_docs=state.get("web_search_docs")
        merged_chunks=rrf_chunks+web_search_docs

        # 之前的score不在关注，reranker会使用大模型来打分
        # chunk 整理一致后再送入大模型
        merged_chunks=[
            {
                "title": chunk.get("item_name") or chunk.get("title"),
                "content": str(chunk.get("content") or ""),
                "url": chunk.get("url") or "",
                "source": chunk.get("source","")
            }
            for chunk in merged_chunks
        ]
        merged_chunks = [chunk for chunk in merged_chunks if chunk["content"]]

        dashscope.base_http_api_url=RerankConfig.rerank_base_url
        dashscope.api_key=RerankConfig.rerank_api_key
        rerank_res = dashscope.TextReRank.call(
            model=RerankConfig.rerank_model,
            query=f"{rewritten_query}",
            documents=[chunk.get("content") for chunk in merged_chunks],
            top_n=len(merged_chunks),
            return_documents=False
        )

        # rerank_res=text_rerank(# 接收这次重排序模型的返回结果
        #     query=rewritten_query,
        #     texts=[ item.get("content") for item in merged_chunks],
        #     limit=len(merged_chunks)
        # ) # 其实现在的结果就已经有了llm的打分，而且已经是按分数降序排序  要把对应分数回填到每个chunk
        # print(json_format(rerank_res))
        """ {"index": 21, "score": 0.2661180055191839 }"""

        # for result in rerank_res.output.get("result",[]):
        #     print(result)
        #     doc_index=int(result.get("index"))
        #     new_score=float(result.get("relevance_score"))
        #     # 在merged_chunks上面修改
        #     doc=merged_chunks[doc_index]
        #     doc["score"]=new_score# 新加一个字段

        for chunk in rerank_res.output.get("results", []):
            merged_chunks[int(chunk.get("index"))]["score"] = float(chunk.get("relevance_score"))

        # for item in rerank_res:
        #     merged_chunks[item["index"]]["score"]=item["score"]# 更新得到最新的merged_chunks

        rerank_chunks=sorted(merged_chunks, key=lambda x: x["score"], reverse=True)

        # todo 阈值指标
        # 动态 TopK：硬上限：最多取前 N 条（<=10）
        RERANK_MAX_TOPK: int = 10
        # 最小 TopK：至少保留前 N 条（>=1，且 <= RERANK_MAX_TOPK）
        RERANK_MIN_TOPK: int = 3  # 总数最少条数
        # 断崖阈值（相对）
        RERANK_GAP_RATIO: float = 0.25
        # 断崖阈值（绝对）
        RERANK_GAP_ABS: float = 0.20

        # 实际取值
        use_max_topk=min(RERANK_MAX_TOPK,len(rerank_chunks))
        use_min_topk=min(RERANK_MIN_TOPK,len(rerank_chunks))

        # for i in range(use_min_topk-1,use_max_topk-1):
        break_idx=use_max_topk
        for i in range(0,use_max_topk-1):
            current_score=rerank_chunks[i]["score"]
            next_score=rerank_chunks[i+1]["score"]

            abs_gap=abs(current_score-next_score) # 绝对差值
            ratio_agp=abs_gap/(current_score+1e-6) # 相对误差
            if ratio_agp>RERANK_GAP_ABS or ratio_agp>RERANK_GAP_RATIO:
                break_idx=i+1
                break
        # 取出break_idx条
        rerank_chunks=rerank_chunks[:]
        return {
            "reranked_docs": rerank_chunks,
        }


